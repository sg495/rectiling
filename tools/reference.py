import sympy as sp

type Laurent = dict[int, int]
type Form = tuple[Laurent, ...]
type SymTier = tuple[Form, Form, bool, bool]
type Move = tuple[int, int, bool]
type Elem = tuple[int, ...]
type Tile = tuple[Elem, Elem, Elem, Elem]
type Tiling = tuple[tuple[int, ...], int, frozenset[Tile]]

INSIDE: Final = 0
FULL_HEIGHT: Final = 1
FULL_WIDTH: Final = 2
FULL: Final = 3
FIT_NAMES: Final = ("inside", "full-height", "full-width", "full")
SYMMETRIES: Final = (
    "identity",
    "flip x->1-x",
    "flip y->1-y",
    "rotation by 180",
    "transpose",
    "anti-transpose",
    "rotation by 90",
    "rotation by 270",
)
X: Final = sp.Symbol("x")


def l_add(p: Laurent, q: Laurent, sign: int = 1) -> Laurent:
    """Returns the sum of a Laurent polynomial and a signed multiple of another."""
    r = dict(p)
    for e, c in q.items():
        v = r.get(e, 0) + sign * c
        if v:
            r[e] = v
        else:
            r.pop(e, None)
    return r


def l_mul(p: Laurent, q: Laurent) -> Laurent:
    """Returns the product of two Laurent polynomials."""
    r: Laurent = {}
    for e, c in p.items():
        for g, d in q.items():
            v = r.get(e + g, 0) + c * d
            if v:
                r[e + g] = v
            else:
                r.pop(e + g, None)
    return r


def l_det(m: list[list[Laurent]]) -> Laurent:
    """Returns the determinant of a square matrix of Laurent polynomials, by Laplace expansion."""
    if len(m) == 1:
        return m[0][0]
    total: Laurent = {}
    for j, entry in enumerate(m[0]):
        if entry:
            minor = [row[:j] + row[j + 1 :] for row in m[1:]]
            total = l_add(total, l_mul(entry, l_det(minor)), -1 if j % 2 else 1)
    return total


def f_add(a: Form, b: Form, sign: int = 1) -> Form:
    """Returns the sum of a linear form and a signed multiple of another."""
    size = max(len(a), len(b))
    return tuple(l_add(a[j] if j < len(a) else {}, b[j] if j < len(b) else {}, sign) for j in range(size))


def f_shift(a: Form, k: int) -> Form:
    """Returns a linear form multiplied by a power of the proportion."""
    return tuple({e + k: c for e, c in p.items()} for p in a)


def admits(tiers: tuple[SymTier, ...], i: int, fit: int, remaining: int, rules: bool) -> bool:
    """Tells whether a placement is allowed with the given number of tiles still to place."""
    if rules:
        if tiers[i][2]:
            return False
        if fit in (FULL_HEIGHT, FULL) and i > 0 and tiers[i - 1][3]:
            return False
    after = len(tiers) + (fit == INSIDE) - (fit == FULL)
    left = remaining - 1
    return left >= after and (after > 0 or left == 0)


def sym_place(
    tiers: tuple[SymTier, ...], i: int, fit: int, tall: bool, nvars: int
) -> tuple[tuple[SymTier, ...], Form | None, int]:
    """Places a tile symbolically, returning the new tiers, the equation imposed and the number of unknowns."""
    floor, wall, _, _ = tiers[i]
    equation: Form | None = None
    if fit == INSIDE:
        side: Form = tuple({} for _ in range(nvars + 1)) + ({0: 1},)
        nvars += 1
        w, h = (side, f_shift(side, 1)) if tall else (f_shift(side, 1), side)
    elif fit == FULL_HEIGHT:
        h = wall
        w = f_shift(h, -1 if tall else 1)
    elif fit == FULL_WIDTH:
        w = floor
        h = f_shift(w, 1 if tall else -1)
    else:
        w, h = floor, wall
        equation = f_add(h, f_shift(w, 1), -1) if tall else f_add(w, f_shift(h, 1), -1)
    new: list[SymTier] = [(u[0], u[1], True, u[3]) for u in tiers[:i]]
    if fit in (FULL_HEIGHT, FULL) and i > 0:
        p = new[i - 1]
        new[i - 1] = (f_add(p[0], w), p[1], False, p[3])
    if fit == INSIDE:
        new.append((w, f_add(wall, h, -1), False, False))
        new.append((f_add(floor, w, -1), h, False, True))
    elif fit == FULL_HEIGHT:
        new.append((f_add(floor, w, -1), wall, False, True))
    elif fit == FULL_WIDTH:
        new.append((floor, f_add(wall, h, -1), False, False))
    rest = list(tiers[i + 1 :])
    if fit in (FULL_WIDTH, FULL) and rest:
        b = rest[0]
        rest[0] = (b[0], f_add(b[1], h), b[2], b[3])
    return tuple(new + rest), equation, nvars


def initial_tiers() -> tuple[SymTier, ...]:
    """Returns the staircase of the empty unit square."""
    return ((({0: 1},), ({0: 1},), False, False),)


@final
class NumberField:
    """Number field generated by a root of an irreducible integer polynomial, with its real embeddings."""

    __slots__ = ("_f", "_d", "_rational", "_roots", "_floors", "_signs", "_powers", "_zero", "_one", "_x")

    _registry: dict[tuple[int, ...], "NumberField"] = {}

    def __new__(cls, f: tuple[int, ...]) -> Self:
        if len(f) < 2 or f[-1] <= 0:
            raise ValueError("Expected ascending coefficients of a non-constant polynomial with positive leading term.")
        self = object.__new__(cls)
        self._f = f
        self._d = len(f) - 1
        self._floors = {}
        self._signs = {}
        self._powers = {}
        self._rational = Fraction(-f[0], f[1]) if self._d == 1 else None
        self._roots = []
        if self._d > 1:
            poly = sp.Poly(list(reversed(f)), X, domain="ZZ")
            for (lo, hi), mult in poly.intervals():
                a, b = Fraction(int(lo.p), int(lo.q)), Fraction(int(hi.p), int(hi.q))
                sa, sb = self._poly_sign(a), self._poly_sign(b)
                if mult != 1 or sa == 0 or sa != -sb:
                    raise ArithmeticError("Isolating interval without a sign change.")
                self._roots.append((a, b, sa))
            self._roots.sort()
            if len(self._roots) != poly.count_roots():
                raise ArithmeticError("Inconsistent count of real roots.")
        self._zero = (1,) + (0,) * self._d
        self._one = self.integer(1)
        self._x = self._reduce([0, 1], 1)
        return self

    @classmethod
    def get(cls, f: tuple[int, ...]) -> "NumberField":
        """Returns the shared field of a minimal polynomial."""
        field = cls._registry.get(f)
        if field is None:
            field = cls._registry[f] = cls(f)
        return field

    @property
    def polynomial(self) -> tuple[int, ...]:
        """Ascending coefficients of the minimal polynomial."""
        return self._f

    @property
    def degree(self) -> int:
        """Degree of the field."""
        return self._d

    @property
    def zero(self) -> Elem:
        """Zero element."""
        return self._zero

    @property
    def one(self) -> Elem:
        """Unit element."""
        return self._one

    @property
    def x(self) -> Elem:
        """Generator of the field."""
        return self._x

    def _poly_sign(self, t: Fraction) -> int:
        """Returns the sign of the minimal polynomial at a rational point."""
        p, q, d = t.numerator, t.denominator, self._d
        v = sum(c * p**i * q ** (d - i) for i, c in enumerate(self._f))
        return (v > 0) - (v < 0)

    def _norm(self, den: int, num: list[int]) -> Elem:
        """Returns the canonical form of a quotient of an integer polynomial by an integer."""
        g = gcd(den, *num)
        if den < 0:
            g = -g
        if g != 1:
            return (den // g, *(v // g for v in num))
        return (den, *num)

    def _reduce(self, num: list[int], den: int) -> Elem:
        """Returns the canonical form of an integer polynomial over an integer, modulo the minimal polynomial."""
        f, d = self._f, self._d
        lead = f[d]
        num = list(num)
        for i in range(len(num) - 1, d - 1, -1):
            if num[i]:
                if lead != 1:
                    num = [v * lead for v in num]
                    den *= lead
                q = num[i] // lead
                for j in range(d + 1):
                    num[i - d + j] -= q * f[j]
        num = num[:d] + [0] * (d - len(num))
        return self._norm(den, num)

    def integer(self, value: int) -> Elem:
        """Returns the element of an integer."""
        return (1, value) + (0,) * (self._d - 1)

    def add(self, a: Elem, b: Elem) -> Elem:
        """Returns a sum."""
        da, db = a[0], b[0]
        if da == db:
            return self._norm(da, [u + v for u, v in zip(a[1:], b[1:])])
        return self._norm(da * db, [u * db + v * da for u, v in zip(a[1:], b[1:])])

    def sub(self, a: Elem, b: Elem) -> Elem:
        """Returns a difference."""
        da, db = a[0], b[0]
        if da == db:
            return self._norm(da, [u - v for u, v in zip(a[1:], b[1:])])
        return self._norm(da * db, [u * db - v * da for u, v in zip(a[1:], b[1:])])

    def mul(self, a: Elem, b: Elem) -> Elem:
        """Returns a product."""
        d = self._d
        num = [0] * (2 * d - 1)
        for i in range(d):
            u = a[i + 1]
            if u:
                for j in range(d):
                    num[i + j] += u * b[j + 1]
        return self._reduce(num, a[0] * b[0])

    def inv(self, a: Elem) -> Elem:
        """Returns an inverse, by the extended Euclidean algorithm over the rationals."""
        r0 = [Fraction(c) for c in self._f]
        r1 = [Fraction(c, a[0]) for c in a[1:]]
        while r1 and r1[-1] == 0:
            r1.pop()
        if not r1:
            raise ZeroDivisionError("Inverse of zero.")
        t0: list[Fraction] = []
        t1 = [Fraction(1)]
        while len(r1) > 1:
            q = [Fraction(0)] * (len(r0) - len(r1) + 1)
            r = list(r0)
            for k in range(len(r0) - len(r1), -1, -1):
                c = r[k + len(r1) - 1] / r1[-1]
                q[k] = c
                for j, v in enumerate(r1):
                    r[k + j] -= c * v
            while r and r[-1] == 0:
                r.pop()
            if not r:
                raise ArithmeticError("Minimal polynomial is not irreducible.")
            t = t0 + [Fraction(0)] * (len(q) + len(t1) - 1 - len(t0))
            for i, u in enumerate(q):
                for j, v in enumerate(t1):
                    t[i + j] -= u * v
            r0, r1, t0, t1 = r1, r, t1, t
        coeffs = [v / r1[0] for v in t1]
        den = 1
        for v in coeffs:
            den = den * v.denominator // gcd(den, v.denominator)
        result = self._reduce([int(v * den) for v in coeffs], den)
        if self.mul(result, a) != self._one:
            raise ArithmeticError("Inverse check failed.")
        return result

    def power(self, e: int) -> Elem:
        """Returns a power of the generator, possibly negative."""
        cached = self._powers.get(e)
        if cached is None:
            if e == 0:
                cached = self._one
            elif e > 0:
                cached = self.mul(self.power(e - 1), self._x)
            elif e == -1:
                cached = self.inv(self._x)
            else:
                cached = self.mul(self.power(e + 1), self.power(-1))
            self._powers[e] = cached
        return cached

    def evaluate(self, p: Laurent) -> Elem:
        """Returns the value of a Laurent polynomial at the generator."""
        total = self._zero
        for e, c in p.items():
            total = self.add(total, self.mul(self.integer(c), self.power(e)))
        return total

    def real_roots(self) -> int:
        """Returns the number of real roots of the minimal polynomial."""
        return 1 if self._d == 1 else len(self._roots)

    def root_floor(self, index: int, bits: int) -> int:
        """Returns the integer part of a real root scaled by a power of two."""
        if self._rational is not None:
            return (self._rational.numerator << bits) // self._rational.denominator
        cached = self._floors.get((index, bits))
        if cached is not None:
            return cached
        lo, hi, s_lo = self._roots[index]
        d, f = self._d, self._f
        below = (lo.numerator << bits) // lo.denominator
        above = -((-hi.numerator << bits) // hi.denominator)
        while above - below > 1:
            m = (below + above) // 2
            t = Fraction(m, 1 << bits)
            if t <= lo:
                below = m
            elif t >= hi:
                above = m
            else:
                v = sum(c * m**i << (bits * (d - i)) for i, c in enumerate(f))
                if v == 0:
                    raise ArithmeticError("Rational root of an irreducible polynomial.")
                if ((v > 0) - (v < 0)) == s_lo:
                    below = m
                else:
                    above = m
        self._floors[(index, bits)] = below
        return below

    def roots_from_one(self) -> list[int]:
        """Returns the indices of the real roots that are at least one."""
        if self._rational is not None:
            return [0] if self._rational >= 1 else []
        return [k for k in range(len(self._roots)) if self.root_floor(k, 8) >= 256]

    def sign(self, a: Elem, index: int) -> int:
        """Returns the sign of an element at a real root that is at least one."""
        num = a[1:]
        if not any(num):
            return 0
        if self._d == 1:
            return 1 if num[0] > 0 else -1
        key = (index, num)
        cached = self._signs.get(key)
        if cached is not None:
            return cached
        top = self._d - 1
        bits = 64
        while True:
            lo = self.root_floor(index, bits)
            if lo < 0:
                raise ArithmeticError("Sign requested at a negative root.")
            hi = lo + 1
            low = high = 0
            for i, c in enumerate(num):
                if c > 0:
                    low += c * lo**i << (bits * (top - i))
                    high += c * hi**i << (bits * (top - i))
                elif c < 0:
                    low += c * hi**i << (bits * (top - i))
                    high += c * lo**i << (bits * (top - i))
            if low > 0 or high < 0:
                result = 1 if low > 0 else -1
                self._signs[key] = result
                return result
            bits *= 2

    def root_value(self, index: int, bits: int = 128) -> Fraction:
        """Returns a rational approximation of a real root."""
        if self._rational is not None:
            return self._rational
        return Fraction(2 * self.root_floor(index, bits) + 1, 1 << (bits + 1))

    def approximate(self, a: Elem, index: int) -> Fraction:
        """Returns a rational approximation of an element at a real root."""
        t = self.root_value(index)
        return sum((Fraction(c, a[0]) * t**i for i, c in enumerate(a[1:])), Fraction(0))


def normalise(p: Laurent) -> tuple[int, ...]:
    """Returns the primitive polynomial with positive leading coefficient sharing the non-zero roots of a Laurent polynomial."""
    if not p:
        return ()
    low, high = min(p), max(p)
    coeffs = [p.get(e, 0) for e in range(low, high + 1)]
    g = gcd(*coeffs)
    if coeffs[-1] < 0:
        g = -g
    return tuple(c // g for c in coeffs)


_candidates: dict[tuple[int, ...], list[tuple[NumberField, list[int]]]] = {}


def candidates(key: tuple[int, ...]) -> list[tuple[NumberField, list[int]]]:
    """Returns the fields of the irreducible factors of a polynomial having roots at least one, with those roots."""
    cached = _candidates.get(key)
    if cached is None:
        cached = []
        if len(key) > 1:
            _, factors = sp.Poly(list(reversed(key)), X, domain="ZZ").factor_list()
            for factor, _ in factors:
                f = [int(c) for c in reversed(factor.all_coeffs())]
                if f[-1] < 0:
                    f = [-c for c in f]
                field = NumberField.get(tuple(f))
                roots = field.roots_from_one()
                if roots:
                    cached.append((field, roots))
        _candidates[key] = cached
    return cached


def solve_sides(field: NumberField, equations: list[Form], k: int, stats: Counter[str]) -> list[Elem] | None:
    """Solves the linear system for the free sides over a number field, if it has a unique solution."""
    zero = field.zero
    rows: list[list[Elem]] = []
    for eq in equations:
        padded = list(eq) + [{}] * (k + 1 - len(eq))
        row = [field.evaluate(padded[j + 1]) for j in range(k)]
        row.append(field.sub(zero, field.evaluate(padded[0])))
        rows.append(row)
    rank = 0
    for col in range(k):
        pivot = next((r for r in range(rank, k + 1) if rows[r][col] != zero), None)
        if pivot is None:
            continue
        rows[rank], rows[pivot] = rows[pivot], rows[rank]
        scale = field.inv(rows[rank][col])
        rows[rank] = [field.mul(v, scale) for v in rows[rank]]
        for r in range(k + 1):
            if r != rank and rows[r][col] != zero:
                c = rows[r][col]
                rows[r] = [field.sub(v, field.mul(c, u)) for v, u in zip(rows[r], rows[rank])]
        rank += 1
    consistent = all(rows[r][k] == zero for r in range(rank, k + 1))
    if rank < k:
        stats["singular"] += 1
        if consistent:
            stats["singular_consistent"] += 1
        return None
    if not consistent:
        raise ArithmeticError("Inconsistent system at a root of its determinant.")
    return [rows[j][k] for j in range(k)]


def concrete_tiles(field: NumberField, moves: tuple[Move, ...], sides: list[Elem]) -> list[Tile]:
    """Replays a placement sequence over a number field, returning the tiles and checking every equation."""
    one, zero, x, xinv = field.one, field.zero, field.x, field.power(-1)
    add, sub, mul = field.add, field.sub, field.mul
    tiers: list[tuple[Elem, Elem, Elem, Elem]] = [(zero, zero, one, one)]
    tiles: list[Tile] = []
    used = 0
    for i, fit, tall in moves:
        ax, ay, floor, wall = tiers[i]
        if fit == INSIDE:
            side = sides[used]
            used += 1
            w, h = (side, mul(x, side)) if tall else (mul(x, side), side)
        elif fit == FULL_HEIGHT:
            h = wall
            w = mul(h, xinv) if tall else mul(h, x)
        elif fit == FULL_WIDTH:
            w = floor
            h = mul(w, x) if tall else mul(w, xinv)
        else:
            w, h = floor, wall
            if (h != mul(x, w)) if tall else (w != mul(x, h)):
                raise ArithmeticError("Equation of a full tile violated by the solution.")
        tiles.append((ax, ay, w, h))
        new = tiers[:i]
        if fit in (FULL_HEIGHT, FULL) and i > 0:
            p = new[i - 1]
            new[i - 1] = (p[0], p[1], add(p[2], w), p[3])
        if fit == INSIDE:
            new.append((ax, add(ay, h), w, sub(wall, h)))
            new.append((add(ax, w), ay, sub(floor, w), h))
        elif fit == FULL_HEIGHT:
            new.append((add(ax, w), ay, sub(floor, w), wall))
        elif fit == FULL_WIDTH:
            new.append((ax, add(ay, h), floor, sub(wall, h)))
        rest = tiers[i + 1 :]
        if fit in (FULL_WIDTH, FULL) and rest:
            b = rest[0]
            rest[0] = (b[0], b[1], b[2], add(b[3], h))
        tiers = new + rest
    if tiers or used != len(sides):
        raise ArithmeticError("Incomplete replay.")
    return tiles


def genuine(field: NumberField, index: int, tiles: frozenset[Tile], n: int) -> bool:
    """Tells whether tiles of positive size form a tiling of the unit square, by exact comparisons."""
    if len(tiles) != n:
        return False
    add, sub, sign, one = field.add, field.sub, field.sign, field.one
    boxes = []
    area = field.zero
    for x0, y0, w, h in tiles:
        x1, y1 = add(x0, w), add(y0, h)
        if sign(x0, index) < 0 or sign(y0, index) < 0 or sign(sub(one, x1), index) < 0 or sign(sub(one, y1), index) < 0:
            return False
        boxes.append((x0, y0, x1, y1))
        area = add(area, field.mul(w, h))
    if area != one:
        return False
    for a in range(len(boxes)):
        ax0, ay0, ax1, ay1 = boxes[a]
        for b in range(a):
            bx0, by0, bx1, by1 = boxes[b]
            apart = (
                sign(sub(bx0, ax1), index) >= 0
                or sign(sub(ax0, bx1), index) >= 0
                or sign(sub(by0, ay1), index) >= 0
                or sign(sub(ay0, by1), index) >= 0
            )
            if not apart:
                return False
    return True


@final
class Search:
    """Depth-first enumeration of placement sequences with orientations, collecting tilings."""

    __slots__ = ("_n", "_rules", "_found", "_verdicts", "_stats")

    def __new__(cls, n: int, rules: bool) -> Self:
        if n < 1:
            raise ValueError("Expected a positive number of tiles.")
        self = object.__new__(cls)
        self._n = n
        self._rules = rules
        self._found = set()
        self._verdicts = {}
        self._stats = Counter()
        return self

    @property
    def found(self) -> set[Tiling]:
        """Tilings found so far."""
        return self._found

    @property
    def stats(self) -> Counter[str]:
        """Counters of the cases met so far."""
        return self._stats

    def prefixes(self, depth: int) -> list[tuple[Move, ...]]:
        """Returns the allowed partial sequences of a given length."""
        out: list[tuple[Move, ...]] = []
        self._walk(initial_tiers(), self._n, (), [], 0, depth, out)
        return out

    def run(self, prefix: tuple[Move, ...] = ()) -> None:
        """Explores all complete sequences extending a partial sequence."""
        tiers = initial_tiers()
        equations: list[Form] = []
        nvars = 0
        for i, fit, tall in prefix:
            tiers, equation, nvars = sym_place(tiers, i, fit, tall, nvars)
            if equation is not None:
                equations.append(equation)
        self._walk(tiers, self._n - len(prefix), prefix, equations, nvars, -1, None)

    def _walk(
        self,
        tiers: tuple[SymTier, ...],
        remaining: int,
        moves: tuple[Move, ...],
        equations: list[Form],
        nvars: int,
        depth: int,
        out: list[tuple[Move, ...]] | None,
    ) -> None:
        """Extends a partial sequence in all allowed ways."""
        if out is not None and len(moves) == depth:
            out.append(moves)
            return
        if not tiers:
            self._solve(moves, equations, nvars)
            return
        for i in range(len(tiers)):
            for fit in range(4):
                if not admits(tiers, i, fit, remaining, self._rules):
                    continue
                for tall in (False, True):
                    new, equation, count = sym_place(tiers, i, fit, tall, nvars)
                    extended = equations + [equation] if equation is not None else equations
                    self._walk(new, remaining - 1, moves + ((i, fit, tall),), extended, count, depth, out)

    def _solve(self, moves: tuple[Move, ...], equations: list[Form], k: int) -> None:
        """Solves a complete sequence exactly and records its tilings."""
        stats = self._stats
        stats["cases"] += 1
        if len(equations) != k + 1:
            raise ArithmeticError("Unexpected number of equations.")
        matrix = [list(eq) + [{}] * (k + 1 - len(eq)) for eq in equations]
        key = normalise(l_det(matrix))
        if not key:
            stats["zero_polynomial"] += 1
            return
        for field, roots in candidates(key):
            sides = solve_sides(field, equations, k, stats)
            if sides is None:
                continue
            tiles = concrete_tiles(field, moves, sides)
            for index in roots:
                if any(field.sign(t[2], index) <= 0 or field.sign(t[3], index) <= 0 for t in tiles):
                    continue
                stats["positive_solutions"] += 1
                tiling: Tiling = (field.polynomial, index, frozenset(tiles))
                verdict = self._verdicts.get(tiling)
                if verdict is None:
                    verdict = self._verdicts[tiling] = genuine(field, index, tiling[2], self._n)
                if verdict:
                    self._found.add(tiling)
                else:
                    stats["not_genuine"] += 1
                    if self._rules:
                        raise ArithmeticError(f"Positive solution of an admissible sequence is not a tiling: {moves}")


def run_task(task: tuple[int, bool, tuple[Move, ...]]) -> tuple[list[Tiling], dict[str, int]]:
    """Explores the sequences extending one partial sequence."""
    n, rules, prefix = task
    search = Search(n, rules)
    search.run(prefix)
    return list(search.found), dict(search.stats)


def enumerate_tilings(n: int, rules: bool, workers: int) -> tuple[set[Tiling], Counter[str]]:
    """Returns all tilings with n tiles and the counters of the search."""
    depth = 3
    if n <= depth or workers <= 1:
        search = Search(n, rules)
        search.run()
        return search.found, search.stats
    tasks = [(n, rules, prefix) for prefix in Search(n, rules).prefixes(depth)]
    found: set[Tiling] = set()
    stats: Counter[str] = Counter()
    with Pool(workers) as pool:
        for tilings, counts in pool.imap_unordered(run_task, tasks, chunksize=1):
            found.update(tilings)
            stats.update(counts)
    return found, stats


def images(field: NumberField, tiles: frozenset[Tile]) -> list[frozenset[Tile]]:
    """Returns the images of a set of tiles under the eight symmetries of the square, in the order of SYMMETRIES."""
    out: list[list[Tile]] = [[] for _ in range(8)]
    one = field.one
    for x0, y0, w, h in tiles:
        fx = field.sub(field.sub(one, x0), w)
        fy = field.sub(field.sub(one, y0), h)
        out[0].append((x0, y0, w, h))
        out[1].append((fx, y0, w, h))
        out[2].append((x0, fy, w, h))
        out[3].append((fx, fy, w, h))
        out[4].append((y0, x0, h, w))
        out[5].append((fy, fx, h, w))
        out[6].append((fy, x0, h, w))
        out[7].append((y0, fx, h, w))
    return [frozenset(o) for o in out]


def cross_points(field: NumberField, tiles: frozenset[Tile]) -> int:
    """Returns the number of points at which four tiles meet."""
    corners: Counter[tuple[Elem, Elem]] = Counter()
    for x0, y0, w, h in tiles:
        x1, y1 = field.add(x0, w), field.add(y0, h)
        corners.update(((x0, y0), (x1, y0), (x0, y1), (x1, y1)))
    if any(v > 4 for v in corners.values()):
        raise ArithmeticError("More than four tiles share a corner.")
    return sum(1 for v in corners.values() if v == 4)


def bag(field: NumberField, index: int, tiles: frozenset[Tile]) -> tuple[Elem, ...]:
    """Returns the sorted multiset of the short sides of some tiles."""
    return tuple(sorted(w if field.sign(field.sub(w, h), index) <= 0 else h for _, _, w, h in tiles))


def polynomial_string(f: tuple[int, ...]) -> str:
    """Returns a polynomial as text, from ascending coefficients."""
    parts: list[str] = []
    for e in range(len(f) - 1, -1, -1):
        c = f[e]
        if c == 0:
            continue
        mono = "" if e == 0 else ("x" if e == 1 else f"x^{e}")
        body = f"{abs(c)}*{mono}" if mono and abs(c) != 1 else (mono or str(abs(c)))
        parts.append(("-" if c < 0 else "") + body if not parts else ("- " if c < 0 else "+ ") + body)
    return " ".join(parts)


def decimal(value: Fraction, digits: int) -> str:
    """Returns a rational number rounded to a number of decimal places."""
    scaled = round(value * 10**digits)
    sign = "-" if scaled < 0 else ""
    whole, frac = divmod(abs(scaled), 10**digits)
    return f"{sign}{whole}.{frac:0{digits}d}"


def analyse(n: int, mode: str, found: set[Tiling], stats: Counter[str], elapsed: float, out: Path, listing: bool) -> dict[str, object]:
    """Computes all counts for a set of tilings and writes the output files."""
    fixed = [0] * 8
    orbits: set[frozenset[Tiling]] = set()
    bags: set[tuple[tuple[int, ...], int, tuple[Elem, ...]]] = set()
    crosses: Counter[int] = Counter()
    per: dict[tuple[tuple[int, ...], int], dict[str, set[object]]] = {}
    stabilisers: dict[Tiling, list[int]] = {}
    for tiling in found:
        f, index, tiles = tiling
        field = NumberField.get(f)
        if not genuine(field, index, tiles, n):
            raise ArithmeticError("Recorded tiling is not genuine.")
        mapped = [(f, index, image) for image in images(field, tiles)]
        if any(m not in found for m in mapped):
            raise ArithmeticError("Set of tilings is not closed under the symmetries of the square.")
        stabilisers[tiling] = [g for g in range(8) if mapped[g] == tiling]
        for g in stabilisers[tiling]:
            fixed[g] += 1
        orbit = frozenset(mapped)
        if len(orbit) * len(stabilisers[tiling]) != 8:
            raise ArithmeticError("Orbit-stabiliser relation violated.")
        orbits.add(orbit)
        key = (f, index, bag(field, index, tiles))
        bags.add(key)
        crosses[cross_points(field, tiles)] += 1
        entry = per.setdefault((f, index), {"tilings": set(), "orbits": set(), "bags": set()})
        entry["tilings"].add(tiling)
        entry["orbits"].add(orbit)
        entry["bags"].add(key)
    if sum(len(o) for o in orbits) != len(found):
        raise ArithmeticError("Orbits do not partition the tilings.")
    if sum(fixed) % 8 or sum(fixed) // 8 != len(orbits):
        raise ArithmeticError("Burnside count disagrees with the orbit count.")
    proportions = sorted(per, key=lambda p: NumberField.get(p[0]).root_value(p[1]))
    rows = ["minimal_polynomial\troot_index\troot\tdegree\ttilings\torbits\tbags"]
    for f, index in proportions:
        field = NumberField.get(f)
        entry = per[(f, index)]
        rows.append(
            f"{polynomial_string(f)}\t{index}\t{decimal(field.root_value(index), 12)}\t{field.degree}"
            f"\t{len(entry['tilings'])}\t{len(entry['orbits'])}\t{len(entry['bags'])}"
        )
    (out / f"proportions_n{n}_mode{mode}.tsv").write_text("\n".join(rows) + "\n")
    digest = hashlib.sha256()
    for line in sorted(repr((t[0], t[1], sorted(t[2]))) for t in found):
        digest.update(line.encode())
    unit = sum(1 for t in found if t[0] == (-1, 1))
    summary: dict[str, object] = {
        "n": n,
        "mode": mode,
        "a_proportions": len(proportions),
        "t_tilings": len(found),
        "b_orbits": len(orbits),
        "b_burnside": sum(fixed) // 8,
        "c_bags": len(bags),
        "fixed": dict(zip(SYMMETRIES, fixed)),
        "tilings_with_proportion_one": unit,
        "tilings_with_cross_point": sum(v for k, v in crosses.items() if k > 0),
        "cross_point_histogram": {str(k): crosses[k] for k in sorted(crosses)},
        "sequences": stats["cases"] // 2**n,
        "cases": stats["cases"],
        "zero_polynomial_cases": stats["zero_polynomial"],
        "singular_cases": stats["singular"],
        "singular_consistent_cases": stats["singular_consistent"],
        "positive_solutions": stats["positive_solutions"],
        "positive_solutions_not_genuine": stats["not_genuine"],
        "tilings_sha256": digest.hexdigest(),
        "seconds": round(elapsed, 2),
    }
    (out / f"summary_n{n}_mode{mode}.json").write_text(json.dumps(summary, indent=2) + "\n")
    if listing:
        write_listing(n, mode, orbits, stabilisers, out)
    return summary


def write_listing(n: int, mode: str, orbits: set[frozenset[Tiling]], stabilisers: dict[Tiling, list[int]], out: Path) -> None:
    """Writes one representative of every orbit, with approximate coordinates."""

    def coordinates(tiling: Tiling) -> list[tuple[str, str, str, str, str]]:
        field = NumberField.get(tiling[0])
        index = tiling[1]
        rows = []
        for tile in tiling[2]:
            x0, y0, w, h = (field.approximate(v, index) for v in tile)
            s = field.sign(field.sub(tile[2], tile[3]), index)
            rows.append((y0, x0, decimal(x0, 6), decimal(y0, 6), decimal(w, 6), decimal(h, 6), ("square", "wide", "tall")[s]))
        return [r[2:] for r in sorted(rows)]

    entries = []
    for orbit in orbits:
        rep = min(orbit, key=lambda t: (-len(stabilisers[t]), coordinates(t)))
        field = NumberField.get(rep[0])
        entries.append((field.root_value(rep[1]), coordinates(rep), rep, len(orbit)))
    entries.sort(key=lambda e: (e[0], e[1]))
    lines = [f"Orbit representatives of the tilings of the unit square by {n} similar rectangles (mode {mode}): {len(entries)} orbits", ""]
    for k, (value, coords, rep, size) in enumerate(entries, 1):
        lines.append(
            f"#{k}  proportion {decimal(value, 12)}  minimal polynomial {polynomial_string(rep[0])} (real root index {rep[1]})"
        )
        lines.append(f"    orbit size {size}; stabiliser of this representative: {', '.join(SYMMETRIES[g] for g in stabilisers[rep])}")
        for x0, y0, w, h, kind in coords:
            lines.append(f"    x0={x0} y0={y0} width={w} height={h} {kind}")
        lines.append("")
    (out / f"orbits_n{n}_mode{mode}.txt").write_text("\n".join(lines))


def main() -> None:
    """Runs the enumeration for the requested numbers of tiles."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("n", type=int, nargs="+")
    parser.add_argument("--mode", choices=("A", "B"), default="A")
    parser.add_argument("--workers", type=int, default=8)
    parser.add_argument("--out", type=Path, default=Path(__file__).parent / "out")
    parser.add_argument("--list", action="store_true", dest="listing")
    args = parser.parse_args()
    if not 1 <= args.workers <= 8:
        parser.error("workers must be between 1 and 8")
    args.out.mkdir(parents=True, exist_ok=True)
    for n in args.n:
        start = time.perf_counter()
        found, stats = enumerate_tilings(n, args.mode == "A", args.workers)
        elapsed = time.perf_counter() - start
        summary = analyse(n, args.mode, found, stats, elapsed, args.out, args.listing or n == 4)
        print(json.dumps(summary), flush=True)


if __name__ == "__main__":
    main()
